function defineService(input: ServiceInput): Service {
  const { motif, galleryMotifs = [], reviews, faqs = [], ...rest } = input;
  const cheapest = [...rest.packages].sort((a, b) => a.price - b.price)[0];
  const rating = reviews.length ? Math.round((reviews.reduce((s, r) => s + r.rating, 0) / reviews.length) * 10) / 10 : 0;
  return {
    ...rest,
    startingPrice: cheapest.price,
    durationMinutes: Math.min(...rest.packages.map((p) => p.durationMinutes)),
    rating,
    reviewCount: reviews.length,
    reviews: reviews.map((r, i) => ({ ...r, id: `${rest.id}-r${i + 1}` })),
    faqs: [...faqs, ...commonFaqs],
    media: [motif, ...galleryMotifs].map((m, i) => ({
      motif: m,
      alt: t(`${rest.name.ar} – صورة ${i + 1}`, `${rest.name.en} – image ${i + 1}`),
    })),
  };
}

